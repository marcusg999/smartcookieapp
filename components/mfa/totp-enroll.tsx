"use client";

import { Copy, Download, ShieldCheck } from "lucide-react";
import { useRouter } from "next/navigation";
import { useActionState, useEffect, useState, useTransition } from "react";

import { generateRecoveryCodes, startTotpEnrollment, verifyTotp } from "@/app/admin/mfa/actions";
import { FormMessage } from "@/components/auth/form-message";
import { Button } from "@/components/ui/button";

import { TotpCodeField } from "./totp-code-field";

type Enrollment = { factorId: string; qrCode: string; secret: string };

/**
 * TOTP enrollment: QR code (+ manual key) → verify a code → one-time backup
 * codes. Used for staff (mandatory) and optionally by parents.
 */
export function TotpEnroll({ doneHref }: { doneHref: string }) {
  const router = useRouter();
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [startError, setStartError] = useState<string | null>(null);
  const [codes, setCodes] = useState<string[] | null>(null);
  const [codesError, setCodesError] = useState<string | null>(null);
  const [state, action, pending] = useActionState(verifyTotp, null);
  const [, startTransition] = useTransition();

  useEffect(() => {
    startTransition(async () => {
      const result = await startTotpEnrollment();
      if (result.ok && result.data) setEnrollment(result.data);
      else setStartError(result.ok ? "Setup failed." : result.message);
    });
  }, []);

  useEffect(() => {
    if (!state?.ok) return;
    startTransition(async () => {
      const result = await generateRecoveryCodes();
      if (result.ok && result.data) setCodes(result.data.codes);
      else setCodesError(result.ok ? null : result.message);
    });
  }, [state]);

  if (startError) return <FormMessage state={{ ok: false, error: "unknown", message: startError }} />;
  if (!enrollment) return <p className="text-sm text-muted-foreground">Preparing your setup code…</p>;

  if (state?.ok) {
    return (
      <div className="space-y-4">
        <p role="status" className="flex items-center gap-2 font-medium">
          <ShieldCheck aria-hidden="true" className="size-5 text-primary" />
          Two-factor authentication is on.
        </p>
        {codes ? (
          <div className="space-y-3">
            <p className="text-sm">
              Save these backup codes somewhere safe. Each works once if you lose your phone. You won&apos;t see them
              again.
            </p>
            <ul
              className="grid grid-cols-2 gap-2 rounded-md border bg-muted p-3 font-mono text-sm"
              aria-label="Backup codes"
            >
              {codes.map((code) => (
                <li key={code}>{code}</li>
              ))}
            </ul>
            <div className="flex flex-wrap gap-2">
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={() => navigator.clipboard.writeText(codes.join("\n"))}
              >
                <Copy aria-hidden="true" /> Copy
              </Button>
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={() => {
                  const url = URL.createObjectURL(new Blob([codes.join("\n")], { type: "text/plain" }));
                  const a = Object.assign(document.createElement("a"), {
                    href: url,
                    download: "smart-cookie-backup-codes.txt",
                  });
                  a.click();
                  URL.revokeObjectURL(url);
                }}
              >
                <Download aria-hidden="true" /> Download
              </Button>
            </div>
          </div>
        ) : codesError ? (
          <p className="text-sm text-muted-foreground">{codesError}</p>
        ) : (
          <p className="text-sm text-muted-foreground">Creating backup codes…</p>
        )}
        <Button
          type="button"
          onClick={() => {
            router.replace(doneHref);
            router.refresh();
          }}
        >
          {codes ? "I've saved my codes, continue" : "Continue"}
        </Button>
      </div>
    );
  }

  return (
    <div className="space-y-5">
      <ol className="list-decimal space-y-4 pl-5 text-sm">
        <li>
          Open an authenticator app (1Password, Google Authenticator, Authy…) and scan this code:
          {/* QR is an SVG data URL generated by Supabase Auth (allowed by img-src data:). */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={enrollment.qrCode}
            alt="QR code for your authenticator app"
            width={176}
            height={176}
            className="mt-3 rounded-md border bg-white p-2"
          />
          <p className="mt-2 text-muted-foreground">
            Can&apos;t scan? Enter this key:{" "}
            <code className="rounded bg-muted px-1.5 py-0.5 break-all" data-testid="totp-secret">
              {enrollment.secret}
            </code>
          </p>
        </li>
        <li>Enter the 6-digit code the app shows.</li>
      </ol>
      <form action={action} className="space-y-4">
        <input type="hidden" name="factorId" value={enrollment.factorId} />
        <input type="hidden" name="purpose" value="enroll" />
        <TotpCodeField error={state && !state.ok ? state.fieldErrors?.code : undefined} />
        <FormMessage state={state} />
        <Button type="submit" disabled={pending}>
          {pending ? "Verifying…" : "Verify and turn on"}
        </Button>
      </form>
    </div>
  );
}
